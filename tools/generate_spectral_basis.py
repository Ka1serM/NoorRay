import re
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import Bounds, LinearConstraint, minimize

ROOT = Path(__file__).resolve().parent.parent
CIE_HEADER = ROOT / "src/NoorRay/Spectral/CieTables.h"
OUTPUT = ROOT / "src/NoorRay/Spectral/BasisTable.h"
LAMBDA_MIN = 360.0
LAMBDA_MAX = 830.0
STEP = 5.0

XYZ_TO_SRGB = np.array([[3.2404542, -1.5371385, -0.4985314], [-0.9692660, 1.8760108, 0.0415560], [0.0556434, -0.2040259, 1.0572252]])
BRADFORD = np.array([[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]])
D65_WHITE = np.array([0.95047, 1.0, 1.08883])


def read_table(text, name):
    match = re.search(name + r"\{(.*?)\};", text, re.S)
    return np.array([float(value.strip().rstrip("f")) for value in match.group(1).split(",") if value.strip()])


def film_matrix(cie):
    cone_scale = (BRADFORD @ D65_WHITE) / (BRADFORD @ np.ones(3))
    adaptation = np.linalg.inv(BRADFORD) @ np.diag(cone_scale) @ BRADFORD
    film = XYZ_TO_SRGB @ adaptation @ cie
    white = film.sum(axis=1)
    return film / white[:, None]


def interpolation_matrix(fine, coarse):
    matrix = np.zeros((len(fine), len(coarse)))
    for row, wavelength in enumerate(fine):
        position = (wavelength - coarse[0]) / STEP
        index = min(int(position), len(coarse) - 2)
        weight = position - index
        matrix[row, index] = 1.0 - weight
        matrix[row, index + 1] = weight
    return matrix


def solve_basis(film, interpolation, count):
    projection = film @ interpolation
    second_difference = np.diff(np.eye(count), n=2, axis=0)
    smoothness = second_difference.T @ second_difference

    hessian = np.kron(np.eye(3), 2.0 * smoothness)
    roundtrip = np.kron(np.eye(3), projection)
    partition = np.kron(np.ones((1, 3)), np.eye(count))
    constraint = LinearConstraint(np.vstack([roundtrip, partition]), np.concatenate([np.eye(3).ravel(), np.ones(count)]),
                                  np.concatenate([np.eye(3).ravel(), np.ones(count)]))
    result = minimize(lambda values: 0.5 * values @ hessian @ values, np.full(3 * count, 1.0 / 3.0), jac=lambda values: hessian @ values,
                      hess=lambda values: hessian, method="trust-constr", constraints=[constraint], bounds=Bounds(0.0, 1.0),
                      options={"maxiter": 20000, "gtol": 1e-12, "xtol": 1e-14})
    if result.status not in (1, 2):
        sys.exit(f"the basis optimization failed: {result.message}")
    basis = result.x.reshape(3, count)
    error = np.abs(projection @ basis.T - np.eye(3)).max()
    if error > 1e-5:
        sys.exit(f"the basis round trip error is {error}")
    return np.clip(basis, 0.0, 1.0)


def write_header(basis, count):
    lines = ["#pragma once", "", "#include <array>", "#include <cstddef>", "",
             "//! Generated by tools/generate_spectral_basis.py: smooth non-negative linear sRGB basis spectra that sum to one.",
             "namespace NoorRay::Spectral {", "",
             f"inline constexpr float basisLambdaMin = {LAMBDA_MIN:.1f}f;",
             f"inline constexpr float basisLambdaStep = {STEP:.1f}f;",
             f"inline constexpr std::size_t basisSampleCount = {count};", ""]
    for name, values in zip(("basisRed", "basisGreen", "basisBlue"), basis):
        lines.append(f"inline constexpr std::array<float, basisSampleCount> {name}{{")
        for start in range(0, count, 8):
            lines.append("    " + ", ".join(f"{value:.8f}f" for value in values[start:start + 8]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n")


def main():
    text = CIE_HEADER.read_text()
    cie = np.stack([read_table(text, name) for name in ("cieX", "cieY", "cieZ")])
    fine = LAMBDA_MIN + np.arange(cie.shape[1])
    coarse = np.arange(LAMBDA_MIN, LAMBDA_MAX + STEP / 2, STEP)
    basis = solve_basis(film_matrix(cie), interpolation_matrix(fine, coarse), len(coarse))
    write_header(basis, len(coarse))


if __name__ == "__main__":
    main()
